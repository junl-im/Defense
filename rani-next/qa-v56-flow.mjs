// Verify actual region/lord selection, back navigation, ships and loading.
import assert from 'node:assert/strict';
import {CDP,getJSON} from '../engines/fiefdom/tools/e2e/cdp.mjs';
const host=process.argv[2]||'http://127.0.0.1:8931/',port=process.argv[3]||'9341';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const v=await getJSON('http://127.0.0.1:'+port+'/json/version');
const c=new CDP();await c.connect(v.webSocketDebuggerUrl);
const {targetId}=await c.send('Target.createTarget',{url:'about:blank'});
const {sessionId:s}=await c.send('Target.attachToTarget',{targetId,flatten:true});
await c.send('Page.enable',{},s);await c.send('Runtime.enable',{},s);
const ev=async expression=>{const r=await c.send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true},s);
 if(r.exceptionDetails)throw Error(r.exceptionDetails.exception?.description);return r.result.value;};
const wait=async x=>{for(let i=0;i<270;i++){if(await ev(x))return;await sleep(300);}throw Error('Timeout '+x);};
await c.send('Page.navigate',{url:host},s);
await wait("!!document.querySelector('#rk-start-now')&&!!document.querySelector('#rani-map-picker')");
assert.ok(await ev("getComputedStyle(document.querySelector('#rani-map-picker')).display==='none'"));
await ev("document.querySelector('#rk-start-now').click()");
await wait("document.querySelector('#menu').classList.contains('rk-choose-region')");
assert.ok(await ev("document.querySelector('#rani-map-picker').open"));
await ev("document.querySelectorAll('#rani-map-picker .map')[1].click()");
const choice=await ev("document.querySelector('#rani-map-picker .map.on h3').textContent");
assert.notEqual(choice,'푸른 해안');
await ev("document.querySelector('#menu button.rk-manual-start').click()");
await wait("!!document.querySelector('#lords .go')");
assert.equal(await ev("document.querySelector('#lords h1').textContent"),choice.toUpperCase());
await ev("document.querySelector('#lords .back').click()");
await wait("document.querySelector('#menu').style.display!=='none'");
assert.equal(await ev("document.querySelector('#rani-map-picker .map.on h3').textContent"),choice);
await ev("document.querySelector('#rk-region-back').click()");
assert.ok(await ev("!document.querySelector('#menu').classList.contains('rk-choose-region')"));
await ev("document.querySelector('#rk-start-now').click()");
await ev("document.querySelector('#rani-map-picker .map').click()");
await ev("document.querySelector('#menu button.rk-manual-start').click()");
await wait("!!document.querySelector('#lords .go')");
await ev("document.querySelector('#lords .go').click()");
await wait("!!window.__game&&!!document.querySelector('.rk-load-bar')");
const out=await ev("(()=>{const g=window.__game,l=document.querySelector('#loading');return {keep:g.state.buildings.some(b=>b.name==='keep'),ships:g.rkSeaShips.length,progress:Number(l.getAttribute('aria-valuenow')),logo:!!l.querySelector('.rk-load-logo')}})()");
assert.ok(out.keep&&out.ships>0&&out.progress===100&&out.logo,out);
console.log('PASS v5.6: region/lords/back, progress and coastal ships',out);
await c.send('Target.closeTarget',{targetId});process.exit(0);