const RES_NAMES = {"wood":"목재","stone":"석재","food":"식량","gold":"금화","influence":"영향력"};

/** compact cost string for buttons/tooltips */
export function fmtCost(cost) {
  if (!cost) return '';
  return Object.entries(cost)
    .map(([k, v]) => `${Math.ceil(v)} ${RES_NAMES[k] || k}`)
    .join(' · ');
}
