import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const checkOnly = process.argv.includes('--check');
const readJson = (file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const packagePath = path.join(root, 'package.json');
const pkg = readJson('package.json');
const EXPECTED_RELEASE_VERSION = '1.0.49';
if (pkg.version !== EXPECTED_RELEASE_VERSION) {
  throw new Error(`v149 package identity mismatch before generation: expected ${EXPECTED_RELEASE_VERSION}, actual ${pkg.version || '<missing>'}. Apply the v1.0.49 direct-root patch including package.json and package-lock.json.`);
}
const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(String(pkg.version || ''));
if (!match) throw new Error(`invalid package version: ${pkg.version}`);
const patch = Number(match[3]);
const buildEpoch = Number(pkg.dokkaebi?.buildEpoch || 24);
const buildRevision = patch;
const buildId = `b${buildEpoch}.${buildRevision}`;
const cacheRevision = `${pkg.version}-${buildId}`;
const lineageVersion = String(pkg.dokkaebi?.lineageVersion || '23.12.0');
const versionPolicy = String(pkg.dokkaebi?.versionPolicy || 'DD-VERSION-POLICY-1.0');
const identity = Object.freeze({
  releaseVersion: pkg.version,
  lineageVersion,
  buildEpoch,
  buildRevision,
  buildId,
  versionPolicy,
  cacheRevision
});

const files = new Map();
files.set('src/release-identity.generated.js', `// Generated by scripts/generate-release-identity-v149.mjs. Do not edit manually.\nexport const RELEASE_IDENTITY = Object.freeze(${JSON.stringify(identity, null, 2)});\nexport const RELEASE_VERSION = RELEASE_IDENTITY.releaseVersion;\nexport const LINEAGE_VERSION = RELEASE_IDENTITY.lineageVersion;\nexport const BUILD_EPOCH = RELEASE_IDENTITY.buildEpoch;\nexport const BUILD_REVISION = RELEASE_IDENTITY.buildRevision;\nexport const BUILD_ID = RELEASE_IDENTITY.buildId;\nexport const CACHE_REVISION = RELEASE_IDENTITY.cacheRevision;\n`);
files.set('public/release-identity.generated.js', `// Generated by scripts/generate-release-identity-v149.mjs. Do not edit manually.\n(() => {\n  const identity = Object.freeze(${JSON.stringify(identity, null, 2)});\n  globalThis.__DOKKAEBI_RELEASE_IDENTITY__ = identity;\n})();\n`);
files.set('public/version.json', `${JSON.stringify(identity, null, 2)}\n`);

const nextPkg = structuredClone(pkg);
nextPkg.dokkaebi = { ...(nextPkg.dokkaebi || {}), ...identity };
const nextPackageText = `${JSON.stringify(nextPkg, null, 2)}\n`;

const lock = readJson('package-lock.json');
lock.version = identity.releaseVersion;
lock.packages ||= {};
lock.packages[''] ||= {};
lock.packages[''].version = identity.releaseVersion;
lock.packages[''].dokkaebi = { ...(lock.packages[''].dokkaebi || {}), ...identity };
lock.dokkaebi = { ...(lock.dokkaebi || {}), ...identity };
const nextLockText = `${JSON.stringify(lock, null, 2)}\n`;

const failures = [];
const compare = (file, expected) => {
  const absolute = path.join(root, file);
  const actual = fs.existsSync(absolute) ? fs.readFileSync(absolute, 'utf8') : '';
  if (actual !== expected) failures.push(file);
};

if (checkOnly) {
  compare('package.json', nextPackageText);
  compare('package-lock.json', nextLockText);
  for (const [file, text] of files) compare(file, text);
  if (failures.length) throw new Error(`v149 release identity outputs are stale: ${failures.join(', ')}`);
  console.log(`PASS v1.0.49 generated release identity (${identity.releaseVersion} / ${identity.buildId})`);
} else {
  fs.writeFileSync(packagePath, nextPackageText);
  fs.writeFileSync(path.join(root, 'package-lock.json'), nextLockText);
  for (const [file, text] of files) {
    const absolute = path.join(root, file);
    fs.mkdirSync(path.dirname(absolute), { recursive: true });
    fs.writeFileSync(absolute, text);
  }
  console.log(JSON.stringify({ id: 'DD-RELEASE-IDENTITY-GENERATOR-V149', ...identity, files: [...files.keys()] }, null, 2));
}
