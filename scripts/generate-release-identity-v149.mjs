import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const checkOnly = process.argv.includes('--check');
const selfTest = process.argv.includes('--self-test');
const packagePath = path.join(root, 'package.json');
const lockPath = path.join(root, 'package-lock.json');
const readJson = (file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));

const TARGET_IDENTITY = Object.freeze({
  releaseVersion: '1.0.49',
  lineageVersion: '23.12.0',
  buildEpoch: 24,
  buildRevision: 49,
  buildId: 'b24.49',
  versionPolicy: 'DD-VERSION-POLICY-1.0',
  cacheRevision: '1.0.49-b24.49'
});
const ALLOWED_SOURCE_VERSIONS = new Set(['1.0.46', '1.0.47', '1.0.48', '1.0.49']);

function validateSourcePackage(pkg) {
  if (pkg?.name !== 'dokkaebi-luck-defense-3d') {
    throw new Error(`v149 identity sync refused: unexpected package name ${pkg?.name || '<missing>'}`);
  }
  if (!ALLOWED_SOURCE_VERSIONS.has(String(pkg.version || ''))) {
    throw new Error(`v149 identity sync refused: supported source versions are 1.0.46-1.0.49, actual ${pkg.version || '<missing>'}`);
  }
}

function createOutputs(pkg, lock) {
  validateSourcePackage(pkg);
  const identity = TARGET_IDENTITY;
  const nextPkg = structuredClone(pkg);
  nextPkg.version = identity.releaseVersion;
  nextPkg.dokkaebi = { ...(nextPkg.dokkaebi || {}), ...identity };

  const nextLock = structuredClone(lock);
  nextLock.version = identity.releaseVersion;
  nextLock.packages ||= {};
  nextLock.packages[''] ||= {};
  nextLock.packages[''].version = identity.releaseVersion;
  nextLock.packages[''].dokkaebi = { ...(nextLock.packages[''].dokkaebi || {}), ...identity };
  nextLock.dokkaebi = { ...(nextLock.dokkaebi || {}), ...identity };

  const files = new Map();
  files.set('package.json', `${JSON.stringify(nextPkg, null, 2)}\n`);
  files.set('package-lock.json', `${JSON.stringify(nextLock, null, 2)}\n`);
  files.set('src/release-identity.generated.js', `// Generated by scripts/generate-release-identity-v149.mjs. Do not edit manually.\nexport const RELEASE_IDENTITY = Object.freeze(${JSON.stringify(identity, null, 2)});\nexport const RELEASE_VERSION = RELEASE_IDENTITY.releaseVersion;\nexport const LINEAGE_VERSION = RELEASE_IDENTITY.lineageVersion;\nexport const BUILD_EPOCH = RELEASE_IDENTITY.buildEpoch;\nexport const BUILD_REVISION = RELEASE_IDENTITY.buildRevision;\nexport const BUILD_ID = RELEASE_IDENTITY.buildId;\nexport const CACHE_REVISION = RELEASE_IDENTITY.cacheRevision;\n`);
  files.set('public/release-identity.generated.js', `// Generated by scripts/generate-release-identity-v149.mjs. Do not edit manually.\n(() => {\n  const identity = Object.freeze(${JSON.stringify(identity, null, 2)});\n  globalThis.__DOKKAEBI_RELEASE_IDENTITY__ = identity;\n})();\n`);
  files.set('public/version.json', `${JSON.stringify(identity, null, 2)}\n`);
  return { identity, files, sourceVersion: String(pkg.version || '') };
}

function runSelfTest() {
  const fixturePackage = {
    name: 'dokkaebi-luck-defense-3d',
    version: '1.0.46',
    scripts: { verify: 'node scripts/verify-project.mjs' },
    dependencies: { three: '^0.183.2' },
    dokkaebi: { releaseVersion: '1.0.46', buildId: 'b24.46' }
  };
  const fixtureLock = {
    name: fixturePackage.name,
    version: '1.0.46',
    lockfileVersion: 3,
    packages: { '': { name: fixturePackage.name, version: '1.0.46' } }
  };
  const { files } = createOutputs(fixturePackage, fixtureLock);
  const generatedPackage = JSON.parse(files.get('package.json'));
  const generatedLock = JSON.parse(files.get('package-lock.json'));
  if (generatedPackage.version !== TARGET_IDENTITY.releaseVersion) throw new Error('self-test package version was not repaired');
  if (generatedLock.version !== TARGET_IDENTITY.releaseVersion || generatedLock.packages?.['']?.version !== TARGET_IDENTITY.releaseVersion) {
    throw new Error('self-test package-lock version was not repaired');
  }
  if (generatedPackage.dependencies?.three !== fixturePackage.dependencies.three) throw new Error('self-test dependencies were not preserved');
  let refused = false;
  try { createOutputs({ ...fixturePackage, version: '9.9.9' }, fixtureLock); } catch { refused = true; }
  if (!refused) throw new Error('self-test unsupported source version was not refused');
  console.log('PASS v1.0.49 release identity self-heal fixture (1.0.46 -> 1.0.49)');
}

if (selfTest) {
  runSelfTest();
  process.exit(0);
}

const pkg = readJson('package.json');
const lock = readJson('package-lock.json');
const { identity, files, sourceVersion } = createOutputs(pkg, lock);
const stale = [];
for (const [file, expected] of files) {
  const absolute = path.join(root, file);
  const actual = fs.existsSync(absolute) ? fs.readFileSync(absolute, 'utf8') : '';
  if (actual !== expected) stale.push(file);
}

if (checkOnly) {
  if (stale.length) throw new Error(`v149 release identity outputs are stale: ${stale.join(', ')}`);
  console.log(`PASS v1.0.49 generated release identity (${identity.releaseVersion} / ${identity.buildId})`);
} else {
  for (const [file, text] of files) {
    const absolute = path.join(root, file);
    fs.mkdirSync(path.dirname(absolute), { recursive: true });
    fs.writeFileSync(absolute, text);
  }
  const action = sourceVersion === identity.releaseVersion ? 'confirmed' : `repaired-${sourceVersion}-to-${identity.releaseVersion}`;
  console.log(JSON.stringify({ id: 'DD-RELEASE-IDENTITY-GENERATOR-V149', action, ...identity, files: [...files.keys()] }, null, 2));
}
