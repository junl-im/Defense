import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { replayDeviceTraceSuiteV146 } from '../src/runtime/device-trace-assurance-v146.js';
const root = path.resolve(import.meta.dirname, '..');
const fixture = JSON.parse(fs.readFileSync(path.join(root, 'docs/qa/device-viewport-traces-v146.json'), 'utf8'));
const report = replayDeviceTraceSuiteV146(fixture);
assert.equal(report.traceCount, 3);
assert.equal(report.passed, true, JSON.stringify(report.failedTraceIds));
const ios = report.reports.find((entry) => entry.traceId === 'ios-safari-standalone-resume');
const chrome = report.reports.find((entry) => entry.traceId === 'android-chrome-address-bar-collapse');
const keyboard = report.reports.find((entry) => entry.traceId === 'android-virtual-keyboard-cycle');
assert.ok(ios.resumeCount >= 1);
assert.ok(chrome.browserChromeFrames >= 1);
assert.ok(keyboard.keyboardFrames >= 1);
const broken = structuredClone(fixture);
broken.traces[2].events[1].expected.keyboard = false;
assert.equal(replayDeviceTraceSuiteV146(broken).passed, false);
console.log('PASS v1.0.46 real-device viewport trace import and deterministic replay');
