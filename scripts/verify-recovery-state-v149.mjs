import { RecoveryStateV149 } from '../src/runtime/recovery-state-v149.js';
import { RunStateCoordinatorV149 } from '../src/runtime/run-state-coordinator-v149.js';
const assert = (value, message) => { if (!value) throw new Error(message); };
const recovery = new RecoveryStateV149({ maxDeveloperEvents: 8, now: () => 1700000000000 });
const begin = recovery.begin('asset-pipeline/private/path', 'file:///home/runner/secret.glb failed');
assert(begin.user.title === '자동 복구 중', 'user recovery title mismatch');
assert(!JSON.stringify(begin.user).includes('asset-pipeline') && !JSON.stringify(begin.user).includes('runner'), 'developer details leaked into user recovery message');
recovery.restore('asset-pipeline', 'fallback loaded');
for (let i = 0; i < 20; i += 1) recovery.degrade(`source-${i}`, `detail-${i}`);
assert(recovery.diagnostics.retainedDeveloperEvents === 8, 'developer recovery history must be bounded');
assert(recovery.diagnostics.failures === 20 && recovery.getUserMessage().state === 'degraded', 'recovery diagnostics mismatch');
const run = new RunStateCoordinatorV149({ initial: 'title', maxTransitions: 16 });
run.observe({ from: 'title', to: 'playing', valid: true, source: 'start' });
run.observe({ from: 'playing', to: 'paused', valid: true, source: 'visibility' });
run.observe({ from: 'paused', to: 'playing', valid: true, source: 'resume' });
run.observe({ from: 'playing', to: 'result', valid: true, source: 'finish' });
assert(run.diagnostics.runStarts === 1 && run.diagnostics.runFinishes === 1, 'run boundary counts mismatch');
assert(run.diagnostics.pauseCount === 1 && run.diagnostics.resumeCount === 1, 'pause/resume counts mismatch');
console.log('PASS v1.0.49 user recovery copy is isolated from bounded developer diagnostics and run-state transitions');
