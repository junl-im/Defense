import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = process.cwd();
const failures = [];
const pass = (m) => console.log(`PASS ${m}`);
const check = (c,m) => { if (!c) failures.push(m); };
const text = (f) => readFileSync(path.join(root,f),'utf8');
const json = (f) => JSON.parse(text(f));

const pkg=json('package.json');
const lock=json('package-lock.json');
const version=json('public/version.json');
const main=text('src/main.js');
const index=text('index.html');
const catalog=text('src/engine/asset-catalog.js');
const pipeline=text('src/engine/asset-pipeline.js');
const visual=text('src/runtime/visual-integration-director.js');
const approval=text('src/runtime/art-approval-pipeline-v115.js');
const sw=text('public/sw.js');

check(pkg.version==='1.0.15' && pkg.dokkaebi?.buildId==='b24.15','release identity mismatch');
check(lock.version===pkg.version && lock.packages?.['']?.dokkaebi?.buildId==='b24.15','lock identity mismatch');
check(version.releaseVersion==='1.0.15' && version.buildId==='b24.15','public identity mismatch');
check(main.includes("const GAME_VERSION = '1.0.15'"),'runtime identity mismatch');
check(index.includes("RELEASE_VERSION = '1.0.15'") && index.includes("BUILD_ID = 'b24.15'"),'boot identity mismatch');
if(!failures.length) pass('v1.0.15 / b24.15 identity is synchronized');

check(!index.includes('alt="푸른 도깨비불과 곤봉을 든 도깨비 수호대 마스코트"'),'floating mascot alt copy remains');
check(index.includes('role="img" aria-label="푸른 도깨비 수호대 마스코트"'),'accessible mascot label missing');
check(index.includes('title-mascot-lite-v112.webp?rev=release-v115-b24-15'),'lite mascot is not first paint');
check(visual.includes("image.alt = ''") && visual.includes('mascot.hidden = true'),'broken image text fail-safe missing');
if(!failures.length) pass('title mascot never exposes floating alternative text and keeps an accessible parent label');

check(catalog.includes('BOOT_ASSET_CATALOG') && catalog.includes('DEFERRED_ASSET_CATALOG'),'staged catalog missing');
check(main.includes('startDeferredAssetPreload') && main.includes('waitForDeferredAssets'),'staged runtime loading missing');
check(pipeline.includes('const workerLimit') && pipeline.includes('cached-'),'parallel cached preload missing');
check(sw.includes('const OPTIONAL_WARM_ASSETS') && sw.includes('DOKKAEBI_WARM_OPTIONAL'),'optional service worker warm path missing');
const shellBlock=sw.slice(sw.indexOf('const SHELL_ASSETS'),sw.indexOf('const OPTIONAL_WARM_ASSETS'));
check(!shellBlock.includes('visual-v114/characters'),'heavy combat art still blocks service worker install');
check(!shellBlock.includes('visual-v112/directional'),'prototype atlas still blocks service worker install');
if(!failures.length) pass('critical-first boot, concurrent deferred loading and lightweight service-worker install are active');

check(approval.includes("version: '1.0.15'") && approval.includes('approvedRuntime'),'approval pipeline missing');
check(approval.includes('autoGeneratedDirectionalRuntimeAllowed: false'),'directional quarantine rule missing');
check(pkg.scripts?.verify?.includes('verify:release:v115'),'full verification chain omits v115');
for(const f of ['docs/PATCH_NOTES_v1.0.15.md','docs/PATCH_APPLY_v1.0.15.md']) check(existsSync(path.join(root,f)),`missing ${f}`);
if(!failures.length) pass('25 approved runtime assets and four quarantined prototype atlases remain explicitly separated');

if(failures.length){ for(const f of failures) console.error(`FAIL ${f}`); console.error(`\nv1.0.15 verification failed with ${failures.length} issue(s).`); process.exit(1); }
console.log('\nv1.0.15 Fast Boot and Art Approval Pipeline verified.');
