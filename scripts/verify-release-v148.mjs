for (const file of ['docs/DELIVERY_RESULT_RULE.md','docs/CI_VERSION_IDENTITY_SYNC_HOTFIX_v1.0.48.md','docs/PATCH_NOTES_v1.0.48.md','docs/RELEASE_ASSURANCE_v1.0.48.md','docs/PATCH_APPLY_v1.0.48.md','docs/NEXT_UPDATE_v1.0.49.md','docs/generated/system-audit-v148.json','docs/generated/system-audit-v148.md']) check(fs.existsSync(path.join(root, file)), `document ${file}`);
