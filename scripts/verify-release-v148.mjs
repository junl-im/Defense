check(budget.id === 'DD-PERFORMANCE-GUARD-V148' && budget.maxRegressionPercent === 5, 'performance guard budget');
check(sw.includes("importScripts('./release-identity.generated.js')") && sw.includes('DD-SW-UPGRADE-ASSURANCE-V148'), 'service worker identity lineage');
check(chain.includes("'148'"), 'dist chain includes v148');
check(workflow.includes('logs/qa/v148') && workflow.includes('v1.0.48-system-integrity'), 'CI v148 evidence upload');
