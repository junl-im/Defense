import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const bootstrapRun = spawnSync(process.execPath, [path.join(root, 'scripts/bootstrap-release-package-v149.mjs')], { cwd: root, encoding: 'utf8' });
process.stdout.write(bootstrapRun.stdout || '');
process.stderr.write(bootstrapRun.stderr || '');
if (bootstrapRun.error || bootstrapRun.status !== 0) {
  throw new Error(`v149 identity bootstrap failed (${bootstrapRun.error?.code || bootstrapRun.status})`);
}
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const json = (file) => JSON.parse(read(file));
const pkg = json('package.json');
const lock = json('package-lock.json');
const version = json('public/version.json');
const generated = read('src/release-identity.generated.js');
const publicGenerated = read('public/release-identity.generated.js');
const main = read('src/main.js');
const policy = read('src/version-policy.js');
const html = read('index.html');
const sw = read('public/sw.js');
const bootstrap = read('public/static-bootstrap.js');
const failures = [];
const check = (value, label) => { if (!value) failures.push(label); };
const revision = Number(String(pkg.version || '').split('.')[2]);
const expectedBuild = `b24.${revision}`;
const expectedCache = `${pkg.version}-${expectedBuild}`;
check(pkg.version === '1.0.49' && revision === 49, 'package release version');
check(pkg.dokkaebi?.releaseVersion === pkg.version && pkg.dokkaebi?.buildId === expectedBuild && pkg.dokkaebi?.cacheRevision === expectedCache, 'package release metadata');
check(lock.version === pkg.version && lock.packages?.['']?.version === pkg.version && lock.packages?.['']?.dokkaebi?.buildId === expectedBuild, 'package-lock release metadata');
check(version.releaseVersion === pkg.version && version.buildId === expectedBuild && version.cacheRevision === expectedCache, 'public version identity');
check(generated.includes(`"releaseVersion": "${pkg.version}"`) && generated.includes(`"buildId": "${expectedBuild}"`), 'source generated identity');
check(publicGenerated.includes(`"cacheRevision": "${expectedCache}"`) && publicGenerated.includes('__DOKKAEBI_RELEASE_IDENTITY__'), 'public generated identity');
check(policy.includes("from './release-identity.generated.js'") && policy.includes('PUBLIC_GAME_VERSION = RELEASE_VERSION'), 'version policy consumes generated identity');
check(main.includes('const GAME_VERSION = PUBLIC_GAME_VERSION;') && !/^[^/\n]*const GAME_VERSION = '\d/m.test(main), 'main consumes version policy without active literal');
check(html.includes('<script src="./release-identity.generated.js"></script>') && html.includes('releaseIdentity.cacheRevision') && html.includes('src="./src/bootstrap.js"'), 'HTML consumes generated identity');
check(sw.startsWith("// const RELEASE_VERSION = '1.0.49';") && sw.includes("importScripts('./release-identity.generated.js')") && sw.includes('RELEASE_IDENTITY.releaseVersion'), 'service worker consumes generated identity');
check(bootstrap.includes('globalThis.__DOKKAEBI_RELEASE_IDENTITY__') && bootstrap.includes('identity.cacheRevision'), 'static bootstrap consumes generated identity');
const run = spawnSync(process.execPath, [path.join(root, 'scripts/generate-release-identity-v149.mjs'), '--check'], { cwd: root, encoding: 'utf8' });
process.stdout.write(run.stdout || ''); process.stderr.write(run.stderr || '');
check(!run.error && run.status === 0, 'generated identity freshness');
const selfTest = spawnSync(process.execPath, [path.join(root, 'scripts/generate-release-identity-v149.mjs'), '--self-test'], { cwd: root, encoding: 'utf8' });
process.stdout.write(selfTest.stdout || ''); process.stderr.write(selfTest.stderr || '');
check(!selfTest.error && selfTest.status === 0, 'identity self-heal fixture');
if (failures.length) {
  console.error(`INFO identity values package=${pkg.version || '<missing>'}, lock=${lock.version || '<missing>'}, public=${version.releaseVersion || '<missing>'}, expected=1.0.49`);
  failures.forEach((failure) => console.error(`FAIL ${failure}`));
  process.exit(1);
}
console.log(`PASS v1.0.49 self-healing generated identity (${pkg.version} / ${expectedBuild} / ${expectedCache})`);
